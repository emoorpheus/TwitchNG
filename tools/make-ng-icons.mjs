// make-ng-icons.mjs - Twitch NG UI icons: the vendored Lucide SVGs (brand/twitchng/src/icons/lucide, ISC, see LICENSE there)
// -> brand/twitchng/web/ng-icons.css: each upstream icon-font class (and a few ng-ico-* helpers) becomes a CSS mask filled with
// currentColor, so icons follow the text colour / focus state like the old font did, but in one consistent outline style.
// Style (owner pick, pre-release 06: variant B "sharp"): square line caps, mitred joins, square rect corners (rx / ry dropped),
// stroke 2.5 - crisper at TV distance than Lucide's round default. --style round = the stock Lucide look.
// Usage: node tools/make-ng-icons.mjs [--style sharp|round] [--stroke 2.5]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'brand/twitchng/src/icons/lucide'), OUT = path.join(ROOT, 'brand/twitchng/web/ng-icons.css');
const argv = process.argv.slice(2), opt = (k, d) => (argv.indexOf(k) >= 0 ? argv[argv.indexOf(k) + 1] : d);
const STYLE = opt('--style', 'sharp'), STROKE = opt('--stroke', STYLE === 'sharp' ? '2.5' : '2.25');
if (!/^(sharp|round)$/.test(STYLE) || !/^\d(\.\d+)?$/.test(STROKE)) { console.error('bad --style / --stroke'); process.exit(2); }
// upstream class (icons.css / main.js) -> Lucide icon
const MAP = [
    ['icon-search', 'search'], ['icon-user', 'user-round'], ['icon-play', 'radio'], ['icon-star', 'star'],
    ['icon-gamepad', 'gamepad-2'], ['icon-movie-play', 'square-play'], ['icon-movie', 'clapperboard'], ['icon-history', 'history'],
    ['icon-blocked', 'ban'], ['icon-arrow-left', 'chevron-left'], ['icon-refresh', 'refresh-cw'], ['icon-options', 'ellipsis-vertical'],
    // side-menu bottom entries have no icon element upstream: ng-ico-* is set on them by the app layer
    ['ng-ico-settings', 'settings'], ['ng-ico-about', 'info'], ['ng-ico-controls', 'keyboard'], ['ng-ico-exit', 'power'],
    ['ng-ico-news', 'sparkles'], ['ng-ico-viewers', 'users'], ['ng-ico-eye', 'eye'],
    // switch rows (a game's / channel's Videos - Clips - Follow, "Play all")
    ['icon-play-1', 'play'], ['icon-heart-o', 'heart']
];
const uri = (name) => {
    let svg = fs.readFileSync(path.join(SRC, name + '.svg'), 'utf8').replace(/<!--[\s\S]*?-->/g, '').replace(/\s*class="[^"]*"/, '')
        .replace(/stroke="currentColor"/, 'stroke="#000"').replace(/stroke-width="[^"]*"/, 'stroke-width="' + STROKE + '"');
    if (STYLE === 'sharp') {
        svg = svg.replace(/stroke-linecap="round"/, 'stroke-linecap="square"').replace(/stroke-linejoin="round"/, 'stroke-linejoin="miter"')
            .replace(/(<rect\b[^>]*?)\s+r[xy]="[^"]*"/g, '$1').replace(/(<rect\b[^>]*?)\s+r[xy]="[^"]*"/g, '$1');
        if (!/stroke-linecap="square"/.test(svg) || !/stroke-linejoin="miter"/.test(svg)) throw new Error(name + ': no round caps / joins to replace');
    }
    svg = svg.replace(/\s+/g, ' ').trim();
    return 'data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64');
};
// icon-* (upstream font classes) are replaced inside an .ng-icons container (the app layer sets it per area while the redesign
// rolls out) and in the grid switch cells (.stream_cell_period: built by main.js, CSS-only so there is no unstyled first frame);
// ng-ico-* are our own helper classes and work anywhere under html.ng-ui
let css = '/* ng-icons.css - GENERATED by tools/make-ng-icons.mjs (--style ' + STYLE + ' --stroke ' + STROKE + ') from brand/twitchng/src/icons/lucide\n' +
    ' * (Lucide, ISC). Do not edit. */\n';
for (const [cls, name] of MAP) {
    const sel = cls.startsWith('icon-') ? ['.ng-icons', '.stream_cell_period'].map((c) => 'html.ng-ui ' + c + ' .' + cls + '::before').join(', ')
        : 'html.ng-ui .' + cls + '::before';
    css += sel + ' { content: "" !important; font-family: inherit !important; display: inline-block; width: 1em; height: 1em; vertical-align: -.14em;\n' +
        '    background-color: currentColor; -webkit-mask: url("' + uri(name) + '") center / contain no-repeat; }\n';
}
fs.writeFileSync(OUT, css);
console.log('ng-icons.css: ' + MAP.length + ' icons, ' + css.length + ' bytes, style ' + STYLE + ', stroke ' + STROKE);
